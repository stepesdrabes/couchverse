// Writes src/generated/czechia.ts from the server's copy of Czechia's border
// (backend/internal/feature/couchtv/czechia.geojson), so the weather map draws the outline the
// server credits, and src/generated/kraje.ts from the kraje beside it (kraje.geojson, written
// by scripts/kraje.mjs), whose warned areas the map fills. test/unit/geo.test.ts fails when a
// module and its source drift apart.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const here = import.meta.dirname;
const data = resolve(here, '../../../backend/internal/feature/couchtv');
const pairs = (ring) => ring.map(([lon, lat]) => `[${lon}, ${lat}]`).join(', ');

const ring = JSON.parse(readFileSync(`${data}/czechia.geojson`, 'utf8')).features[0].geometry
	.coordinates[0];
const out = resolve(here, '../src/generated/czechia.ts');
writeFileSync(
	out,
	'// Generated by `npm run outline` from backend/internal/feature/couchtv/czechia.geojson. Do not edit.\n' +
		'// geoBoundaries CZE ADM0 (boundary data by ČÚZK, CC BY 4.0), simplified; credit it wherever it is\n' +
		'// drawn (WeatherCredits.borders).\n\n' +
		"/** Czechia's border as [longitude, latitude] points, closed: the last point is the first. */\n" +
		`export const CZECHIA: readonly (readonly [number, number])[] = [${pairs(ring)}];\n`
);
console.log(`wrote ${out}`);

const kraje = JSON.parse(readFileSync(`${data}/kraje.geojson`, 'utf8')).features;
const entries = kraje.map(
	(f) =>
		`\t'${f.properties.iso}': [\n${f.geometry.coordinates.map((r) => `\t\t[${pairs(r)}]`).join(',\n')}\n\t]`
);
const outK = resolve(here, '../src/generated/kraje.ts');
writeFileSync(
	outK,
	'// Generated by `npm run outline` from backend/internal/feature/couchtv/kraje.geojson. Do not edit.\n' +
		'// geoBoundaries CZE ADM1 (boundary data by ČÚZK, CC BY 4.0), simplified with every border between\n' +
		'// two kraje shared; credit it wherever it is drawn (WeatherCredits.borders).\n\n' +
		"import type { KrajCode } from '../spec';\n\n" +
		'/** Each kraj by its ISO 3166-2 code: its outer ring, then its holes, as closed [longitude, latitude] rings. */\n' +
		'export const KRAJE: Readonly<Record<KrajCode, readonly (readonly (readonly [number, number])[])[]>> = {\n' +
		`${entries.join(',\n')}\n};\n`
);
console.log(`wrote ${outK}`);
