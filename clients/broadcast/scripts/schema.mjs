// Writes contract/broadcast-spec.schema.json from src/spec.ts: the server's specs are checked
// against it, so the TypeScript types stay the single source of the contract.
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { createGenerator } from 'ts-json-schema-generator';

const here = import.meta.dirname;
const schema = createGenerator({
	path: resolve(here, '../src/spec.ts'),
	tsconfig: resolve(here, '../tsconfig.json'),
	type: 'Spec',
	expose: 'export',
	topRef: true,
	jsDoc: 'extended',
	additionalProperties: false,
	sortProps: true,
	skipTypeCheck: true
}).createSchema('Spec');

const { $schema, ...rest } = schema;
const doc = {
	$schema,
	title: 'Couch TV broadcast spec',
	description:
		'Generated by `npm run schema` in clients/broadcast from src/spec.ts. Do not edit. One spec per cutscene template, or a break (its sound only).',
	...rest
};
const out = resolve(here, '../../../contract/broadcast-spec.schema.json');
writeFileSync(out, JSON.stringify(doc, null, '\t') + '\n');
console.log(`wrote ${out}`);
